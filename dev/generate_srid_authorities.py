#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["psycopg[binary]>=3.2"]
# ///
"""Generate the SRID tables in `rust/geodatafusion/src/util/` from PostGIS's `spatial_ref_sys`.

PostGIS SRIDs equal their authority code, and each SRID belongs to one authority (EPSG or
ESRI, plus a few others). `srid_authorities.rs` lists the contiguous SRID ranges per authority, so
`util::srid` can turn an SRID into the right `AUTHORITY:CODE` CRS without a PROJ database.

`srid_lonlat.rs` lists the longitude/latitude SRIDs, the only ones geography accepts, with the
axes of their spheroids, which geography measures on. The spheroids come from each SRID's PROJ
definition: `+a` with `+b` or `+rf`, `+R`, or an `+ellps` or `+datum` name, which `proj -le`
resolves.

Usage:
    dev/postgis.sh start
    uv run dev/generate_srid_authorities.py
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import psycopg

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "rust/geodatafusion/src/util/srid_authorities.rs"
OUT_LONLAT = REPO / "rust/geodatafusion/src/util/srid_lonlat.rs"
DEFAULT_URL = "postgresql://postgres:postgres@localhost:54329/postgres"

QUERY = """
WITH ranked AS (
    SELECT auth_name, srid, srid - row_number() OVER (PARTITION BY auth_name ORDER BY srid) AS run
    FROM spatial_ref_sys
    WHERE auth_name IN ('EPSG', 'ESRI') AND srid = auth_srid
)
SELECT auth_name, min(srid), max(srid)
FROM ranked
GROUP BY auth_name, run
ORDER BY min(srid)
"""

LONLAT_QUERY = """
SELECT srid, proj4text
FROM spatial_ref_sys
WHERE proj4text LIKE '+proj=longlat%'
ORDER BY srid
"""

# The ellipsoids of PROJ's built-in `+datum` names, which `proj` no longer lists.
DATUM_ELLIPSOIDS = {
    "WGS84": "WGS84",
    "GGRS87": "GRS80",
    "NAD83": "GRS80",
    "NAD27": "clrk66",
    "potsdam": "bessel",
    "carthage": "clrk80ign",
    "hermannskogel": "bessel",
    "ire65": "mod_airy",
    "nzgd49": "intl",
    "OSGB36": "airy",
}


def ellipsoids() -> dict[str, tuple[float, float]]:
    """PROJ's named ellipsoids, as their semi-major and semi-minor axes."""
    listing = subprocess.run(["proj", "-le"], check=True, capture_output=True, text=True).stdout
    named = {}
    for line in listing.splitlines():
        name, *parameters = line.split()
        values = dict(p.split("=", 1) for p in parameters[:2] if "=" in p)
        a = float(values["a"])
        named[name] = (a, float(values["b"]) if "b" in values else a - a / float(values["rf"]))
    return named


def spheroid(proj4text: str, named: dict[str, tuple[float, float]]) -> tuple[float, float]:
    """The semi-major and semi-minor axes of a PROJ definition's spheroid."""
    parameters = dict(p.lstrip("+").split("=", 1) for p in proj4text.split() if "=" in p)
    if "R" in parameters:
        radius = float(parameters["R"])
        return radius, radius
    if "a" in parameters:
        a = float(parameters["a"])
        if "b" in parameters:
            return a, float(parameters["b"])
        return a, a - a / float(parameters["rf"])
    if "ellps" in parameters:
        return named[parameters["ellps"]]
    return named[DATUM_ELLIPSOIDS[parameters["datum"]]]


def write_lonlat(version: str, rows: list[tuple[int, str]]) -> int:
    named = ellipsoids()
    ranges: list[list] = []
    for srid, proj4text in rows:
        a, b = spheroid(proj4text, named)
        if ranges and ranges[-1][1] == srid - 1 and ranges[-1][2:] == [a, b]:
            ranges[-1][1] = srid
        else:
            ranges.append([srid, srid, a, b])
    lines = [
        "//! The longitude/latitude SRIDs in PostGIS's `spatial_ref_sys`, with their spheroids.",
        "//!",
        f"//! Generated by `dev/generate_srid_authorities.py` from PostGIS {version}. Don't edit by hand.",
        "",
        "/// Sorted, non-overlapping `(first, last, a, b)` SRID ranges: the semi-major and semi-minor",
        "/// axes of the spheroid, in metres.",
        "pub(crate) const SRID_LONLAT: &[(i32, i32, f64, f64)] = &[",
    ]
    for first, last, a, b in ranges:
        lines.append(f"    ({first}, {last}, {a!r}, {b!r}),")
    lines.append("];")
    OUT_LONLAT.write_text("\n".join(lines) + "\n")
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT_LONLAT)], check=False)
    return len(ranges)


def main() -> int:
    url = os.environ.get("POSTGIS_URL", DEFAULT_URL)
    with psycopg.connect(url) as conn:
        version = conn.execute("SELECT postgis_lib_version()").fetchone()[0]
        ranges = conn.execute(QUERY).fetchall()
        lonlat = conn.execute(LONLAT_QUERY).fetchall()

    lines = [
        "//! SRID ranges per authority, from PostGIS's `spatial_ref_sys`.",
        "//!",
        f"//! Generated by `dev/generate_srid_authorities.py` from PostGIS {version}. Don't edit by hand.",
        "",
        "use crate::util::srid::Authority;",
        "",
        "/// Contiguous, sorted, non-overlapping `(first, last, authority)` SRID ranges.",
        "pub(crate) const SRID_AUTHORITIES: &[(i32, i32, Authority)] = &[",
    ]
    for auth_name, first, last in ranges:
        authority = {"EPSG": "Authority::Epsg", "ESRI": "Authority::Esri"}[auth_name]
        lines.append(f"    ({first}, {last}, {authority}),")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=False)
    print(f"Wrote {len(ranges)} ranges to {OUT.relative_to(REPO)}", file=sys.stderr)
    count = write_lonlat(version, lonlat)
    print(f"Wrote {count} ranges to {OUT_LONLAT.relative_to(REPO)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
